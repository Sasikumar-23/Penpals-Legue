/**
 * Apply translation across the entire DOM
 */
function setSiteLanguage(lang) {
    if (!['en', 'ta'].includes(lang)) lang = 'en';
    localStorage.setItem('ipl_language', lang);
    document.documentElement.lang = lang;

    const dict = IPL_TRANSLATIONS[lang] || IPL_TRANSLATIONS.en;

    // Update buttons
    const btnEN = document.querySelectorAll('#langEN, .lang-btn-en');
    const btnTA = document.querySelectorAll('#langTA, .lang-btn-ta');
    if (lang === 'ta') {
        btnTA.forEach(b => b.classList.add('active'));
        btnEN.forEach(b => b.classList.remove('active'));
    } else {
        btnEN.forEach(b => b.classList.add('active'));
        btnTA.forEach(b => b.classList.remove('active'));
    }

    // 1. Elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            el.textContent = dict[key];
        }
    });

    // 2. Elements with data-i18n-html attribute
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (dict[key]) {
            el.innerHTML = dict[key];
        }
    });

    // 3. Inputs / textareas with data-i18n-placeholder attribute
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) {
            el.setAttribute('placeholder', dict[key]);
        }
    });

    // 4. Fallback smart text mapper for direct HTML text nodes
    applySmartTranslations(lang, dict);

    // Update document title if present
    if (typeof updateTitle === 'function' && typeof currentPage !== 'undefined') {
        updateTitle(currentPage);
    }
}

